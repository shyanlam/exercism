def two_fer(name: str = "you") -> str:
    """Output a message according to:
    https://exercism.org/tracks/python/exercises/two-fer

    :param: name: str.  The name to be used in the output, or 'you' if not given.
    :returns: str.  The output "Out for {name}, one for me."
    """
    return f"One for {name}, one for me."
